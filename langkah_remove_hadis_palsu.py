import pandas as pd, os
RILIS = "/content/dataset_rilis.csv"
OOF   = "/content/oof_prediksi.csv"
LEMBAR = "/content/lembar_telaah_pakar.csv"
OUT   = "/content"

r = pd.read_csv(RILIS)
o = pd.read_csv(OOF)
bad = r[r["tandai_lemah_atau_palsu"].astype(str).str.lower().isin(["true", "1", "ya", "yes"])]
print("Hadis ditandai di dataset_rilis:", len(bad))
bad_urls = set(bad["url"])
o["enam"] = o["url"].isin(bad_urls)
print("Dari enam itu, ada di data model:", int(o["enam"].sum()))
print("Dari enam itu, salah diklasifikasi:", int((o["enam"] & ~o["ok"]).sum()))
print(f"Akurasi semua hadis      (n={len(o)}): {o['ok'].mean():.4f}")
print(f"Akurasi tanpa enam hadis (n={(~o['enam']).sum()}): {o.loc[~o['enam'], 'ok'].mean():.4f}")
try:
    k = pd.read_csv(LEMBAR)
    hit = k[k["url"].isin(bad_urls)]
    print("Dari enam itu, ikut ditelaah pakar:", len(hit))
    print(hit[["no", "url"]].to_string(index=False))
except Exception as e:
    print("Lembar telaah tidak terbaca:", e)
keep = r[~r["url"].isin(bad_urls)]
keep.to_csv(os.path.join(OUT, "dataset_rilis_tanpa_enam.csv"), index=False)
print("Disimpan: dataset_rilis_tanpa_enam.csv ->", len(keep), "baris dari", len(r))

